-- Reconstruye estructura; NO recupera registros perdidos ni carga datos demo.
-- Reejecutable. No elimina tablas, filas ni columnas. También actualiza el
-- esquema anterior conservado en tests/fixtures/schema_anterior.sql.
-- Otros esquemas personalizados requieren revisión previa.
-- Flask necesita SUPABASE_KEY=clave service_role del MISMO proyecto.

begin;
set local lock_timeout = '10s';
set local timezone = 'UTC';

-- gen_random_uuid() está incorporada en PostgreSQL >= 13 (Supabase).
create table if not exists public.users (
    id uuid primary key default gen_random_uuid(),
    full_name text not null,
    email text not null unique,
    phone text,
    password_hash text not null,
    balance numeric(12,2) not null default 0,
    saldo numeric(12,2) not null default 0,
    is_active boolean not null default false,
    activo boolean not null default false,
    rol text not null default 'usuario',
    estado_cuenta text not null default 'pendiente_pago',
    pending_token text default gen_random_uuid()::text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

-- Copiar saldo/actividad SOLO al crear columnas del esquema antiguo.
-- Agregar saldo directamente con default 0 ocultaría el balance anterior:
-- get_wallet_balance() da prioridad a saldo.
do $$
begin
    if not exists (
        select 1 from information_schema.columns
        where table_schema = 'public' and table_name = 'users' and column_name = 'saldo'
    ) then
        alter table public.users add column saldo numeric(12,2);
        update public.users set saldo = balance;
        alter table public.users alter column saldo set default 0;
        alter table public.users alter column saldo set not null;
    end if;
    if not exists (
        select 1 from information_schema.columns
        where table_schema = 'public' and table_name = 'users' and column_name = 'activo'
    ) then
        alter table public.users add column activo boolean;
        update public.users set activo = is_active;
        alter table public.users alter column activo set default false;
        alter table public.users alter column activo set not null;
    end if;
    if not exists (
        select 1 from information_schema.columns
        where table_schema = 'public' and table_name = 'users' and column_name = 'estado_cuenta'
    ) then
        alter table public.users add column estado_cuenta text;
        update public.users set estado_cuenta = case
            when activo then 'activo' else 'pendiente_pago' end;
        alter table public.users alter column estado_cuenta set default 'pendiente_pago';
        alter table public.users alter column estado_cuenta set not null;
    end if;
end $$;

alter table public.users
    add column if not exists rol text not null default 'usuario',
    add column if not exists pending_token text default gen_random_uuid()::text;

create table if not exists public.recargas (
    -- Las rutas <int:recarga_id> necesitan un entero, no UUID.
    -- BY DEFAULT permite importar IDs originales de un respaldo.
    id bigint generated by default as identity primary key,
    user_id uuid not null references public.users(id) on delete cascade,
    valor numeric(12,2) not null,
    tipo text not null,
    estado text not null default 'pendiente',
    observacion text,
    approved_by uuid references public.users(id) on delete set null,
    approved_at timestamptz,
    rejected_at timestamptz,
    created_at timestamptz not null default now()
);

create table if not exists public.balance_transactions (
    id uuid primary key default gen_random_uuid(),
    user_id uuid not null references public.users(id) on delete cascade,
    transaction_type text not null,
    amount numeric(12,2) not null,
    description text,
    reference text,
    created_at timestamptz not null default now()
);

create table if not exists public.people_records (
    id uuid primary key default gen_random_uuid(),
    document_number text not null unique,
    full_name text not null,
    email text,
    phone text,
    city text,
    created_at timestamptz not null default now()
);

create table if not exists public.query_history (
    id uuid primary key default gen_random_uuid(),
    user_id uuid not null references public.users(id) on delete cascade,
    search_term text not null,
    cost numeric(12,2) not null default 0,
    result_count integer not null default 0,
    created_at timestamptz not null default now()
);

create table if not exists public.negative_reports (
    id uuid primary key default gen_random_uuid(),
    -- El formulario actual envía target_document=None deliberadamente.
    target_document text,
    target_name text not null,
    phone text,
    address text,
    department text,
    city text,
    lat double precision,
    lng double precision,
    reason text not null,
    details text,
    status text not null default 'activo',
    created_by uuid references public.users(id) on delete set null,
    created_at timestamptz not null default now()
);

alter table public.negative_reports
    alter column target_document drop not null,
    add column if not exists phone text,
    add column if not exists address text,
    add column if not exists department text,
    add column if not exists city text,
    add column if not exists lat double precision,
    add column if not exists lng double precision;

create index if not exists idx_users_pending_token on public.users(pending_token);
create index if not exists idx_recargas_user_estado_id on public.recargas(user_id, estado, id desc);
create index if not exists idx_recargas_estado_created on public.recargas(estado, created_at);
create index if not exists idx_recargas_estado_approved on public.recargas(estado, approved_at desc);
create index if not exists idx_recargas_approved_by on public.recargas(approved_by);
create index if not exists idx_balance_transactions_user_created on public.balance_transactions(user_id, created_at desc);
create index if not exists idx_query_history_user_created on public.query_history(user_id, created_at desc);
create index if not exists idx_people_records_name on public.people_records(full_name);
create index if not exists idx_negative_reports_document on public.negative_reports(target_document);
create index if not exists idx_negative_reports_status_created on public.negative_reports(status, created_at desc);
create index if not exists idx_negative_reports_author_created on public.negative_reports(created_by, created_at desc);

-- La autenticación NO usa auth.users ni auth.uid(). Solo el servidor accede
-- por API con service_role; los usuarios finales usan las rutas de Flask.
alter table public.users enable row level security;
alter table public.recargas enable row level security;
alter table public.balance_transactions enable row level security;
alter table public.people_records enable row level security;
alter table public.query_history enable row level security;
alter table public.negative_reports enable row level security;

revoke all privileges on table
    public.users, public.recargas, public.balance_transactions,
    public.people_records, public.query_history, public.negative_reports
from public, anon, authenticated;

grant usage on schema public to service_role;
grant select, insert, update, delete on table
    public.users, public.recargas, public.balance_transactions,
    public.people_records, public.query_history, public.negative_reports
to service_role;

-- Resolver el nombre real admite también una recargas anterior con BIGSERIAL.
do $$
declare
    recharge_sequence text := pg_get_serial_sequence('public.recargas', 'id');
begin
    if recharge_sequence is null then
        raise exception 'recargas.id necesita secuencia/IDENTITY. Revisar esquema existente; no se cambiaron sus IDs.';
    end if;
    execute format('revoke all privileges on sequence %s from public, anon, authenticated', recharge_sequence);
    execute format('grant usage, select on sequence %s to service_role', recharge_sequence);
end $$;

notify pgrst, 'reload schema';
commit;
